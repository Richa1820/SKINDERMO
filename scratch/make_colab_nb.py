                "def train_model(arch, img_size):\n",
                "    print(f'\\n========== Retraining {arch.upper()} ==========')\n",
                "    inputs = layers.Input(shape=(img_size, img_size, 3))\n",
                "    if arch == 'resnet50':\n",
                "        from tensorflow.keras.applications.resnet50 import ResNet50, preprocess_input\n",
                "        x = layers.Lambda(preprocess_input)(inputs)\n",
                "        base = ResNet50(include_top=False, weights='imagenet', input_tensor=x)\n",
                "    elif arch == 'densenet121':\n",
                "        from tensorflow.keras.applications.densenet import DenseNet121, preprocess_input\n",
                "        x = layers.Lambda(preprocess_input)(inputs)\n",
                "        base = DenseNet121(include_top=False, weights='imagenet', input_tensor=x)\n",
                "    else:\n",
                "        from tensorflow.keras.applications.inception_v3 import InceptionV3\n",
                "        x = layers.Rescaling(1.0 / 127.5, offset=-1.0)(inputs)\n",
                "        base = InceptionV3(include_top=False, weights='imagenet', input_tensor=x)\n",
                "    base.trainable = False\n",
                "    feat = layers.GlobalAveragePooling2D()(base.output)\n",
                "    feat = layers.BatchNormalization()(feat)\n",
                "    feat = layers.Dropout(0.4)(feat)\n",
                "    feat = layers.Dense(256, activation='relu')(feat)\n",
                "    feat = layers.Dropout(0.3)(feat)\n",
                "    outputs = layers.Dense(NUM_CLASSES, activation='softmax')(feat)\n",
                "    model = models.Model(inputs, outputs)\n",
